#!/usr/bin/env node
/*
 * Build: data/questions.json + config.json -> everything under docs/.
 *   node build.js
 * Node standard library only. Output is deterministic, so rebuilding with
 * unchanged inputs changes nothing in git.
 */
"use strict";
const fs = require("fs");
const path = require("path");
const ics = require("./docs/ics.js");

const ROOT = __dirname;
const OUT = path.join(ROOT, "docs");
const config = JSON.parse(fs.readFileSync(path.join(ROOT, "config.json"), "utf8"));
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data/questions.json"), "utf8"));

if (!/^https?:\/\/.+\/$/.test(config.baseUrl)) {
  throw new Error("config.baseUrl must be an absolute URL ending in /");
}

function esc(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

function datesBetween(a, b) {
  const out = [];
  for (let d = a; d <= b; d = ics.addDays(d, 1)) out.push(d);
  return out;
}

function longDate(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(Date.UTC(y, m - 1, d)).toLocaleDateString("en-US", {
    weekday: "long", month: "long", day: "numeric", year: "numeric", timeZone: "UTC"
  });
}

// Relative path (inside docs/) of the feed file for a feed and start date.
function feedPath(feed, start) {
  return feed.kind === "fixed" ? `feeds/${feed.id}-${feed.start.slice(0, 4)}.ics` : `feeds/${feed.id}/${start}.ics`;
}

const baseOpts = {
  baseUrl: config.baseUrl,
  dtstamp: config.dtstamp,
  uidPrefix: config.uidPrefix,
  alarmTrigger: config.alarmTrigger
};

// 1. Feeds
fs.rmSync(path.join(OUT, "feeds"), { recursive: true, force: true });
let count = 0;
const starts = datesBetween(config.evergreenFirstStart, config.evergreenLastStart);
for (const feed of data.feeds) {
  if (feed.days.length !== 30) throw new Error(`${feed.id} has ${feed.days.length} days, expected 30`);
  const list = feed.kind === "fixed" ? [feed.start] : starts;
  for (const start of list) {
    const rel = feedPath(feed, start);
    const file = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, ics.buildCalendar(feed, start, { ...baseOpts, variant: "sub", feedUrl: config.baseUrl + rel }));
    count++;
  }
}

// 2. Open data
fs.writeFileSync(path.join(OUT, "questions.json"), JSON.stringify(data, null, 2) + "\n");

// 3. What the page script needs (no fetch, so it also works from a file)
const siteData = {
  baseUrl: config.baseUrl,
  evergreenFirstStart: config.evergreenFirstStart,
  evergreenLastStart: config.evergreenLastStart,
  dtstamp: config.dtstamp,
  uidPrefix: config.uidPrefix,
  alarmTrigger: config.alarmTrigger,
  feeds: data.feeds
};
fs.writeFileSync(path.join(OUT, "site-data.js"),
  "/* Generated by build.js from data/questions.json. Do not edit by hand. */\nwindow.QAD = " +
  JSON.stringify(siteData) + ";\n");

// 4. Landing page
function card(feed) {
  const fixed = feed.kind === "fixed";
  const rel = fixed ? feedPath(feed, feed.start) : "";
  const abs = fixed ? config.baseUrl + rel : "";
  const end = fixed ? ics.addDays(feed.start, 29) : "";
  const when = fixed
    ? `<p class="when">${esc(longDate(feed.start))} to ${esc(longDate(end))}. <span data-past-note></span></p>`
    : `<p class="when" data-when>Starts the day after you add it and runs for 30 days.</p>`;
  const subscribe = `
      <div class="buttons" data-sub-buttons ${fixed ? "" : "hidden"}>
        <a class="btn" data-link="apple" href="${fixed ? esc(abs.replace(/^https?:/, "webcal:")) : "#"}">Apple Calendar</a>
        <a class="btn" data-link="google" href="${fixed ? esc("https://calendar.google.com/calendar/render?cid=" + encodeURIComponent(abs.replace(/^https?:/, "webcal:"))) : "#"}" target="_blank" rel="noopener">Google Calendar</a>
        <a class="btn" data-link="outlook" href="${fixed ? esc("https://outlook.live.com/calendar/0/addfromweb?url=" + encodeURIComponent(abs) + "&name=" + encodeURIComponent(feed.calendarName)) : "#"}" target="_blank" rel="noopener">Outlook</a>
        <button class="btn btn-quiet" type="button" data-copy="${esc(abs)}">Copy the link</button>
      </div>
      <p class="copied" data-copied aria-live="polite"></p>`;
  return `
    <section class="feed" id="${esc(feed.id)}" data-feed="${esc(feed.id)}">
      <h2>${esc(feed.name)}</h2>
      <p>${esc(feed.blurb)}</p>
      ${feed.note ? `<p class="note">${esc(feed.note)}</p>` : ""}
      ${when}
      ${fixed ? "" : `<noscript><p class="note">The add buttons work out tomorrow's date, which needs JavaScript. The download below and the printable version do not.</p></noscript>`}
      ${subscribe}
      ${fixed ? `<form class="download" data-download>
        <label>Or, if your app will not add a calendar by link, download the same thirty days as a file</label>
        <span class="row"><button class="btn btn-quiet" type="submit">Download as a file</button></span>
      </form>` : `<form class="download" data-download>
        <label for="start-${esc(feed.id)}">Or download a file that starts on</label>
        <span class="row">
          <input type="date" id="start-${esc(feed.id)}" name="start" required>
          <button class="btn btn-quiet" type="submit">Download</button>
        </span>
      </form>`}
      <p class="small"><a href="print/${esc(feed.id)}.html">Printable version</a> (30 days, with room to write)</p>
      ${feed.credit ? `<p class="small credit">${esc(feed.credit).replace(/(https:\/\/[^\s)]+)/, '<a href="$1">$1</a>')}</p>` : ""}
    </section>`;
}

const tpl = fs.readFileSync(path.join(ROOT, "src/index.template.html"), "utf8");
fs.writeFileSync(path.join(OUT, "index.html"), tpl.replace("<!--FEEDS-->", data.feeds.map(card).join("\n")));

// 5. Printable pages
fs.mkdirSync(path.join(OUT, "print"), { recursive: true });
for (const feed of data.feeds) {
  const items = feed.days.map((d, i) => `
    <li class="day">
      <p class="q"><span class="n">Day ${i + 1}</span> ${esc(d.q)}</p>
      <p class="f"><b>Then:</b> ${esc(d.follow)}</p>
      <p class="t"><b>Tip:</b> ${esc(d.tip)}</p>
      <div class="lines" aria-hidden="true"></div>
    </li>`).join("");
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(feed.name)}: printable</title>
<link rel="stylesheet" href="../print.css">
</head>
<body>
<main>
  <p class="back"><a href="../index.html">Back to A Question a Day</a> <button type="button" onclick="window.print()">Print</button></p>
  <h1>${esc(feed.name)}</h1>
  <p class="intro">One question a day for thirty days. Ask it, then the follow-up, and write down what you hear in their words. ${feed.note ? esc(feed.note) : ""}</p>
  <ol class="days">${items}
  </ol>
  ${feed.credit ? `<p class="credit">${esc(feed.credit)}</p>` : ""}
  <p class="foot">From PureTome, puretome.com. Questions licensed CC BY 4.0.</p>
</main>
</body>
</html>
`;
  fs.writeFileSync(path.join(OUT, "print", feed.id + ".html"), html);
}

console.log(`built ${count} feed files, ${data.feeds.length} printable pages, index.html, questions.json`);
