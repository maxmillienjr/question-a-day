#!/usr/bin/env python3
"""Write docs/years.js from data/years/*.json and the saved source headers.

The page loads years.js with a plain script tag, so it works from the file system
and offline. Only what the page shows goes in: text, question, category, sombre,
source url, and one credit line per source.
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def header(path):
    raw = open(os.path.join(ROOT, path), encoding="utf-8").read()
    head = raw.partition("\n---\n")[0]
    return dict(line.split(": ", 1) for line in head.splitlines() if ": " in line)


def main():
    years, sources = {}, {}
    for p in sorted(glob.glob(os.path.join(ROOT, "data", "years", "*.json"))):
        data = json.load(open(p, encoding="utf-8"))
        out = []
        for it in data["items"]:
            h = header(it["source_file"])
            sources[it["source_url"]] = {"credit": h.get("credit", ""), "licence": h.get("licence", "")}
            out.append({k: it[k] for k in ("category", "text", "question", "source_url", "sombre")})
        years[str(data["year"])] = out
    payload = {"years": years, "sources": sources}
    js = ("// Generated by tools/build.py from data/years/. Do not edit by hand.\n"
          "// Item text: see README.md for licences and credits.\n"
          "window.WORLD_AT_TWENTY = " + json.dumps(payload, ensure_ascii=False, indent=1, sort_keys=True) + ";\n")
    with open(os.path.join(ROOT, "docs", "years.js"), "w", encoding="utf-8") as f:
        f.write(js)
    print(f"docs/years.js: {len(years)} years")


if __name__ == "__main__":
    main()
